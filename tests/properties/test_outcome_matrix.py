"""Property: a task's outcome follows rivet's exit. A failed rivet never leaves a green task, a retryable stop is retried,
a final stop is not, and no exit falls through to a default.

The axes come from code, not from a list: the operators are every `_RivetTask` with a `command`, the exit classes and
the codes are rivet's registry (`docs/reference/errors.md`, generated by `rivet schema errors`) at the pinned ref. The
grade is read by a second reader: the task instance's state in Airflow's metadata database and the calls the fake
`rivet` logged, never the operator's own return value. A cell that is not PASS is in `outcome_known.yaml` with a date
and a reason; an entry whose cell turned PASS, or names no cell, fails like a new RED.
"""

from __future__ import annotations

import datetime
import fnmatch
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest
import yaml
from conftest import RIVET_SRC, SECRET, DagRig

from airflow_provider_rivet import operators

LEDGER = Path(__file__).with_name("outcome_known.yaml")
REASONS = frozenset({"no_stand", "no_cloud", "needs_product_hook", "axis_not_built", "harness_bug"})
RETRIES = 2
BATCH = "source:\n  type: postgres\n  url_env: RIVET_PG_URL\nexports:\n  - {name: a, query: SELECT 1, mode: full}\n"
PLAN = [{"export_name": "a", "prioritization": {"export_recommendation": {"export_name": "a", "recommended_wave": 1}}}]
CDC = "source:\n  type: postgres\n  url_env: RIVET_PG_URL\nexports:\n  - {name: a, mode: cdc}\n"


def registry_text() -> str:
    """rivet's error registry at RIVET_SRC: the checked-out file, else the blob at HEAD (a sparse checkout)."""
    path = RIVET_SRC / "docs" / "reference" / "errors.md"
    if path.exists():
        return path.read_text()
    shown = subprocess.run(["git", "-C", str(RIVET_SRC), "show", "HEAD:docs/reference/errors.md"], capture_output=True, text=True)
    assert shown.returncode == 0, f"rivet's error registry is not at {RIVET_SRC}: set RIVET_SRC to a rivet checkout"
    return shown.stdout


def table_rows(text: str, first: str) -> list[list[str]]:
    """The cells of each row of the Markdown table whose header starts with `first`."""
    rows, inside = [], False
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells[0] == first:
            inside = True
        elif inside and line.startswith("|") and not set(cells[0]) <= {"-"}:
            rows.append(cells)
        elif inside and not line.startswith("|"):
            break
    return rows


REGISTRY = registry_text()
EXITS = sorted(int(row[0]) for row in table_rows(REGISTRY, "exit"))
CODES = [(row[0].strip("`"), row[1], row[2]) for row in table_rows(REGISTRY, "code")]


@dataclass(frozen=True)
class Outcome:
    """What the metadata database and the fake's call log show after the run: the task's state and rivet's calls."""

    state: str
    calls: int


SUCCESS = Outcome("success", 1)
FINAL = Outcome("failed", 1)
RETRIED = Outcome("failed", 1 + RETRIES)
CRASHED = Outcome("failed", 2)


def line(exit_code: int, code: str | None = None) -> dict[str, Any]:
    """rivet's `--json-errors` line for a stop of this exit."""
    return {"error": "stopped", "exit_class": exit_code, **({"code": code} if code else {})}


def exit_cells() -> dict[str, tuple[dict[str, Any], Outcome]]:
    """Each way a rivet process can end, with the outcome rivet's registry and docs/retries.md give it."""
    cells: dict[str, tuple[dict[str, Any], Outcome]] = {"exit0": ({}, SUCCESS)}
    for code in EXITS:
        cells[f"exit{code}"] = ({"exit": code, "line": line(code)}, RETRIED if code == 2 else FINAL)
    cells["exit2-usage"] = ({"exit": 2}, FINAL)
    cells["exit101-panic"] = ({"exit": 101}, FINAL)
    cells["exit7-unknown"] = ({"exit": 7}, FINAL)
    cells["exit137"] = ({"exit": 137}, CRASHED)
    cells["sigkill"] = ({"signal": "SIGKILL"}, CRASHED)
    return cells


def code_cells() -> dict[str, tuple[dict[str, Any], Outcome]]:
    """Each registered code at each exit its kind allows: exit 2 is retried (transient or busy), any other is final."""
    cells = {}
    for code, kind, exits in CODES:
        for exit_code in [2, 1] if kind == "environment" else [int(exits)]:
            cells[f"{code}/exit{exit_code}"] = (
                {"exit": exit_code, "line": line(exit_code, code)},
                RETRIED if exit_code == 2 else FINAL,
            )
    return cells


def commands() -> dict[str, type]:
    """Every operator that runs rivet, by the command it runs."""
    found, todo = {}, [operators._RivetTask]
    while todo:
        cls = todo.pop()
        todo.extend(cls.__subclasses__())
        if cls.__dict__.get("command"):
            found[cls.command] = cls
    return found


@dataclass(frozen=True)
class Harness:
    """How a command's task is built in a DAG file and which fake subcommand its play and calls are under."""

    sub: str
    config: str
    kwargs: str
    spec: dict[str, Any] | None = None


def harness(command: str) -> Harness | None:
    """The harness of a command; None for a command no harness is built for yet (a NOT_GRADED row)."""
    match command:
        case "run":
            return Harness("run", BATCH, "")
        case "apply":
            return Harness("apply", BATCH, "export='a', ")
        case "cdc_run":
            return Harness("run", CDC, "export='a', ")
        case "load":
            return Harness("load", BATCH, "export='a', ")
        case "compact":
            return Harness("compact", BATCH, "export='a', ")
        case "plan":
            return Harness("plan", BATCH, "plan_file=os.path.join(os.environ['PLAN_DIR'], 'plan.json'), ", {"plan_list": PLAN})
        case "init":
            return None
    raise AssertionError(f"`{command}` has no harness case: add one, or a `None` case and a NOT_GRADED ledger entry")


CELLS = {f"{command}/{name}": (command, *cell) for command in commands() for name, cell in exit_cells().items()}
CELLS |= {f"code/{name}": ("run", *cell) for name, cell in code_cells().items()}


def ledger() -> dict[str, dict[str, str]]:
    """The known non-PASS cells, by cell id or glob."""
    return yaml.safe_load(LEDGER.read_text()) or {}


def known(cell: str) -> dict[str, str] | None:
    """The ledger entry covering a cell."""
    hits = [entry for pattern, entry in ledger().items() if fnmatch.fnmatchcase(cell, pattern)]
    assert len(hits) <= 1, f"{cell} is covered by more than one ledger entry"
    return hits[0] if hits else None


def run_cell(dag_rig: DagRig, cell: str, command: str, play: dict[str, Any], tool: Harness) -> Outcome:
    """Build the command's task in a one-task DAG, run it under `dag.test()`, read the metadata DB and the call log."""
    dag_rig.config.write_text(tool.config)
    dag_rig.scenario(**(tool.spec or {}), **({tool.sub: play} if play else {}))
    dag_id = "outcome_" + "".join(c if c.isalnum() else "_" for c in cell)
    cls = commands()[command]
    source = (
        "import datetime, os\n"
        "from airflow import DAG\n"
        f"from airflow_provider_rivet.operators import {cls.__name__}\n"
        f"with DAG({dag_id!r}, start_date=datetime.datetime(2026, 1, 1), schedule=None) as dag:\n"
        f"    {cls.__name__}(task_id='t', config={str(dag_rig.config)!r}, state_dir={str(dag_rig.state_dir)!r}, {tool.kwargs}"
        f"rivet_bin={str(dag_rig.bin / 'rivet')!r}, deployment='local', env={{'RIVET_PG_URL': os.environ['RIVET_PG_URL']}}, "
        f"retries={RETRIES}, retry_delay=datetime.timedelta(0))\n"
    )
    _, states = dag_rig.run_source(dag_id, source, {"RIVET_PG_URL": SECRET, "PLAN_DIR": str(dag_rig.tmp)})
    return Outcome(states["t"], sum(1 for c in dag_rig.calls() if c["argv"][0] == tool.sub))


@pytest.mark.parametrize("cell", sorted(CELLS))
def test_the_task_outcome_follows_rivets_exit(dag_rig: DagRig, cell: str) -> None:
    """PASS: the outcome is the one the exit names. A ledgered cell is still what the ledger says, so it shrinks."""
    command, play, expected = CELLS[cell]
    entry = known(cell)
    tool = harness(command)
    if tool is None:
        assert entry and entry["verdict"] == "NOT_GRADED", f"{cell}: no harness and no NOT_GRADED ledger entry"
        return
    got = run_cell(dag_rig, cell, command, play, tool)
    if entry is None:
        assert got == expected, f"RED {cell}: expected {expected}, the metadata DB and the call log show {got}"
    else:
        assert entry["verdict"] == "RED" and got != expected, f"{cell} is ledgered {entry['verdict']} but grades PASS"


def test_each_ledger_entry_is_dated_reasoned_and_covers_a_cell() -> None:
    """An entry names a verdict, a date, a reason (NOT_GRADED: from the fixed set) and what closes it, and covers a cell."""
    for pattern, entry in ledger().items():
        assert entry["verdict"] in ("RED", "NOT_GRADED"), pattern
        datetime.date.fromisoformat(str(entry["since"]))
        assert len(str(entry["closes"]).strip()) > 20, f"{pattern}: say what turns it PASS"
        if entry["verdict"] == "NOT_GRADED":
            assert entry["reason"] in REASONS, f"{pattern}: `{entry['reason']}` is not one of {sorted(REASONS)}"
        assert any(fnmatch.fnmatchcase(cell, pattern) for cell in CELLS), f"{pattern} covers no cell: drop it"


def test_the_axes_come_from_the_registry() -> None:
    """Every exit class and every code of rivet's registry is a row: no axis is empty or partial."""
    assert EXITS == [1, 2, 3, 4, 5, 6]
    assert len(CODES) == REGISTRY.count("\n| `RIVET_") and CODES
    assert {kind for _, kind, _ in CODES} <= {"usage", "environment", "refusal", "busy", "integrity", "internal"}
